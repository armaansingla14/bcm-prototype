// Runs the randomised fault-scenario set against the state-machine BCM and
// the naive baseline and writes per-scenario results plus a summary.
//
//   scenario_runner [--n 280] [--seed 1] [--out results] [--trace <index>]
#include <algorithm>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <map>
#include <numeric>
#include <string>
#include <vector>

#include "bcm/sim/scenario.hpp"

using namespace bcm::sim;

namespace {

struct Agg {
  std::array<int, kNumReq> scen_with{};  // scenarios with >=1 violation per requirement
  std::array<int, kNumReq> count{};
  int scen_any = 0;
  int total = 0;
  std::vector<int> crash_lat;
  std::vector<uint32_t> busoff_rec;
};

double mean(const std::vector<int>& v) {
  return v.empty() ? 0.0 : std::accumulate(v.begin(), v.end(), 0.0) / static_cast<double>(v.size());
}
double meanu(const std::vector<uint32_t>& v) {
  return v.empty() ? 0.0 : std::accumulate(v.begin(), v.end(), 0.0) / static_cast<double>(v.size());
}
template <typename T>
double pct(std::vector<T> v, double p) {
  if (v.empty()) return 0.0;
  std::sort(v.begin(), v.end());
  const size_t idx = static_cast<size_t>(p * static_cast<double>(v.size() - 1) + 0.5);
  return static_cast<double>(v[idx]);
}

}  // namespace

int main(int argc, char** argv) {
  int n = 280;
  uint64_t seed = 1;
  std::string out = "results";
  int trace = -1;
  for (int i = 1; i < argc; ++i) {
    if (!std::strcmp(argv[i], "--n") && i + 1 < argc) n = std::atoi(argv[++i]);
    else if (!std::strcmp(argv[i], "--seed") && i + 1 < argc) seed = std::strtoull(argv[++i], nullptr, 10);
    else if (!std::strcmp(argv[i], "--out") && i + 1 < argc) out = argv[++i];
    else if (!std::strcmp(argv[i], "--trace") && i + 1 < argc) trace = std::atoi(argv[++i]);
  }

  const auto set = make_scenario_set(n, seed);
  std::ofstream csv(out + "/scenario_results.csv");
  csv << "scenario,fault_class,controller,total";
  for (int r = 0; r < kNumReq; ++r) csv << ',' << to_string(static_cast<Req>(r));
  csv << ",crash_unlock_latency_ms,description\n";

  Agg agg[2];
  std::map<std::string, std::array<int, 3>> by_class;  // scenarios, sm_any, naive_any
  for (size_t i = 0; i < set.size(); ++i) {
    const Scenario& sc = set[i];
    auto& bc = by_class[sc.fault_class];
    bc[0]++;
    for (int k = 0; k < 2; ++k) {
      const ControllerKind kind = k == 0 ? ControllerKind::StateMachine : ControllerKind::Naive;
      std::string tr;
      if (static_cast<int>(i) == trace) tr = out + "/trace_" + sc.name + (k == 0 ? "_sm.csv" : "_naive.csv");
      const RunResult res = run_scenario(sc, kind, tr);
      csv << sc.name << ',' << sc.fault_class << ',' << (k == 0 ? "state_machine" : "naive") << ',' << res.total;
      for (int r = 0; r < kNumReq; ++r) csv << ',' << res.violations[r];
      csv << ',' << res.crash_unlock_latency_ms << ",\"" << sc.description << "\"\n";
      Agg& a = agg[k];
      for (int r = 0; r < kNumReq; ++r) {
        if (res.violations[r] > 0) a.scen_with[r]++;
        a.count[r] += res.violations[r];
      }
      if (res.total > 0) {
        a.scen_any++;
        bc[1 + k]++;
      }
      a.total += res.total;
      if (res.crash_unlock_latency_ms >= 0) a.crash_lat.push_back(res.crash_unlock_latency_ms);
      a.busoff_rec.insert(a.busoff_rec.end(), res.busoff_recovery_ms.begin(), res.busoff_recovery_ms.end());
    }
  }

  std::ofstream md(out + "/summary.md");
  md << "# Fault-scenario results\n\n";
  md << "Generated by `scenario_runner --n " << n << " --seed " << seed << "`. " << set.size()
     << " randomised 120 s drive cycles (simulated), " << fault_classes().size()
     << " fault classes in rotation, identical stimuli for both controllers.\n\n";
  md << "## Requirement violations\n\n";
  md << "| Requirement | Description | SM scenarios | SM count | Naive scenarios | Naive count |\n";
  md << "|---|---|---:|---:|---:|---:|\n";
  for (int r = 0; r < kNumReq; ++r) {
    md << "| " << to_string(static_cast<Req>(r)) << " | " << describe(static_cast<Req>(r)) << " | "
       << agg[0].scen_with[r] << " | " << agg[0].count[r] << " | " << agg[1].scen_with[r] << " | "
       << agg[1].count[r] << " |\n";
  }
  md << "| **Any** | | **" << agg[0].scen_any << "/" << set.size() << "** | **" << agg[0].total << "** | **"
     << agg[1].scen_any << "/" << set.size() << "** | **" << agg[1].total << "** |\n\n";

  md << "## Scenarios with at least one violation, by fault class\n\n";
  md << "| Fault class | Scenarios | State machine | Naive |\n|---|---:|---:|---:|\n";
  for (const auto& fc : fault_classes()) {
    auto it = by_class.find(fc);
    if (it == by_class.end()) continue;
    md << "| " << fc << " | " << it->second[0] << " | " << it->second[1] << " | " << it->second[2] << " |\n";
  }
  md << "\n## Timing metrics\n\n";
  md << "| Metric | State machine | Naive |\n|---|---:|---:|\n";
  char buf[256];
  std::snprintf(buf, sizeof buf, "| Crash unlock latency, mean ms (n) | %.1f (%zu) | %.1f (%zu) |\n",
                mean(agg[0].crash_lat), agg[0].crash_lat.size(), mean(agg[1].crash_lat), agg[1].crash_lat.size());
  md << buf;
  std::snprintf(buf, sizeof buf, "| Crash unlock latency, max ms | %.0f | %.0f |\n", pct(agg[0].crash_lat, 1.0),
                pct(agg[1].crash_lat, 1.0));
  md << buf;
  std::snprintf(buf, sizeof buf, "| Bus-off: fault cleared to first BCM_Status, mean ms (n) | %.1f (%zu) | %.1f (%zu) |\n",
                meanu(agg[0].busoff_rec), agg[0].busoff_rec.size(), meanu(agg[1].busoff_rec),
                agg[1].busoff_rec.size());
  md << buf;
  std::snprintf(buf, sizeof buf, "| Bus-off: fault cleared to first BCM_Status, max ms | %.0f | %.0f |\n",
                pct(agg[0].busoff_rec, 1.0), pct(agg[1].busoff_rec, 1.0));
  md << buf;
  md.close();

  std::printf("scenarios: %zu\n", set.size());
  std::printf("state machine: %d/%zu scenarios with violations, %d violations total\n", agg[0].scen_any, set.size(),
              agg[0].total);
  std::printf("naive        : %d/%zu scenarios with violations, %d violations total\n", agg[1].scen_any, set.size(),
              agg[1].total);
  std::printf("wrote %s/scenario_results.csv and %s/summary.md\n", out.c_str(), out.c_str());
  return 0;
}
